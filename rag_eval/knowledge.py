def bigrams(text):
    """中文按字符 bigram 切，英文按词切，避免分词依赖。"""
    text = text.lower()
    return {text[i:i + 2] for i in range(len(text) - 1)}


def similarity(query, content):
    """bigram Jaccard 相似度。"""
    q = bigrams(query)
    c = bigrams(content)
    if not q or not c:
        return 0.0
    return len(q & c) / len(q)


def retrieve(query, docs, top_k=3):
    """返回按相似度降序排列的 [(doc, score)]。"""
    scored = [(d, similarity(query, d["content"] + d["title"])) for d in docs]
    scored.sort(key=lambda x: x[1], reverse=True)
    return scored[:top_k]
